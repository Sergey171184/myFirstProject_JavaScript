// Создание массива с днями недели (0 - понедельник, 6 - воскресенье)
const week = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье"];

// Получение текущего дня недели (0 - воскресенье, 1 - понедельник, ..., 6 - суббота)
const today = new Date().getDay();

// Преобразование к нашему формату массива (0 -> 6, 1-6 -> 0-5)
// Так как в нашем массиве воскресенье имеет индекс 6, а понедельник - 0
const currentDayIndex = today === 0 ? 6 : today - 1;

// Вывод дней недели
console.log("Дни недели:");
for (let i = 0; i < week.length; i++) {
    // Сначала проверяем, является ли день текущим
    if (i === currentDayIndex) {
        // Текущий день - выводим жирным шрифтом с пометкой "(сегодня)"
        console.log(`%c${week[i]} (сегодня)`, 'font-weight: bold');
    } else if (i === 5 || i === 6) {
        // Выходные дни (суббота и воскресенье) - выводим курсивом с пометкой "(выходной)"
        console.log(`%c${week[i]} (выходной)`, 'font-style: italic');
    } else {
        // Обычные будние дни - стандартное оформление
        console.log(week[i]);
    }
}

alert("Усложненное задание урока 7 выполнено! Проверьте консоль для просмотра результатов.");